               #:else
                  full_data(idata + ${j + 1}$) = IAND(ISHFT(packed_data(ipack + ${w + 1}$), ${-off}$), mask)
               #:endif
            #:endfor
         END DO
         CALL bits2ints_tail(${nb}$, Ndata, packed_data, full_data)
      END SUBROUTINE bits2ints_${nb}$

   #:endfor
! **************************************************************************************************
!> \brief Packs the integers after the last whole group of 64 (fewer than 64 integers).
!> \param Nbits number of bits per integer
!> \param Ndata number of integers including the whole groups
!> \param packed_data the stream of bits
!> \param full_data the integers
! **************************************************************************************************
   SUBROUTINE ints2bits_tail(Nbits, Ndata, packed_data, full_data)
      INTEGER, INTENT(IN)                                :: Nbits, Ndata
      INTEGER(KIND=int_8), INTENT(INOUT)                 :: packed_data(*)
      INTEGER(KIND=int_8), INTENT(IN)                    :: full_data(*)

      INTEGER                                            :: ibit, idata, ipack, ioff, ndone
      INTEGER(KIND=int_8)                                :: mask, data_tmp

      ndone = (Ndata/64)*64
      IF (ndone < Ndata) THEN
         mask = ISHFT(1_int_8, Nbits) - 1 ! all bits if Nbits is 64
         ipack = (ndone/64)*Nbits
         packed_data(ipack + 1:ipack + ((Ndata - ndone)*Nbits + 63)/64) = 0
         ibit = 0
         DO idata = ndone + 1, Ndata
            data_tmp = IAND(full_data(idata), mask)
            ioff = MOD(ibit, 64)
            packed_data(ipack + ibit/64 + 1) = IOR(packed_data(ipack + ibit/64 + 1), ISHFT(data_tmp, ioff))
            IF (ioff + Nbits > 64) packed_data(ipack + ibit/64 + 2) = ISHFT(data_tmp, ioff - 64)
            ibit = ibit + Nbits
         END DO
      END IF
   END SUBROUTINE ints2bits_tail

! **************************************************************************************************
!> \brief Unpacks the integers after the last whole group of 64 (fewer than 64 integers).
!> \param Nbits number of bits per integer
!> \param Ndata number of integers including the whole groups
!> \param packed_data the stream of bits
!> \param full_data the integers
! **************************************************************************************************
   SUBROUTINE bits2ints_tail(Nbits, Ndata, packed_data, full_data)
      INTEGER, INTENT(IN)                                :: Nbits, Ndata
      INTEGER(KIND=int_8), INTENT(IN)                    :: packed_data(*)
      INTEGER(KIND=int_8), INTENT(INOUT)                 :: full_data(*)

      INTEGER                                            :: ibit, idata, ipack, ioff, ndone
      INTEGER(KIND=int_8)                                :: mask, data_tmp

      ndone = (Ndata/64)*64
      IF (ndone < Ndata) THEN
         mask = ISHFT(1_int_8, Nbits) - 1 ! all bits if Nbits is 64
         ipack = (ndone/64)*Nbits
         ibit = 0
         DO idata = ndone + 1, Ndata
            ioff = MOD(ibit, 64)
            data_tmp = ISHFT(packed_data(ipack + ibit/64 + 1), -ioff)
            IF (ioff + Nbits > 64) data_tmp = IOR(data_tmp, ISHFT(packed_data(ipack + ibit/64 + 2), 64 - ioff))
            full_data(idata) = IAND(data_tmp, mask)
            ibit = ibit + Nbits
         END DO
      END IF
   END SUBROUTINE bits2ints_tail

END MODULE hfx_compression_core_methods
