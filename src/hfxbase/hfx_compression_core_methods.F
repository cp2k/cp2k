               #:endif
            #:endfor
         END DO
         CALL bits2ints_tail(${nb}$, Ndata, packed_data, full_data)
      END SUBROUTINE bits2ints_${nb}$

   #:endfor
! **************************************************************************************************
!> \brief Packs the integers after the last whole group of 64 (fewer than 64 integers).
!> \param Nbits number of bits per integer
!> \param Ndata number of integers including the whole groups
!> \param packed_data the stream of bits
!> \param full_data the integers
! **************************************************************************************************
   SUBROUTINE ints2bits_tail(Nbits, Ndata, packed_data, full_data)
      INTEGER, INTENT(IN)                                :: Nbits, Ndata
      INTEGER(KIND=int_8), INTENT(INOUT)                 :: packed_data(*)
      INTEGER(KIND=int_8), INTENT(IN)                    :: full_data(*)

      INTEGER                                            :: ibit, idata, ipack, ioff, ndone
      INTEGER(KIND=int_8)                                :: mask, data_tmp

      ndone = (Ndata/64)*64
      IF (ndone < Ndata) THEN
         mask = ISHFT(1_int_8, Nbits) - 1 ! all bits if Nbits is 64
         ipack = (ndone/64)*Nbits
         packed_data(ipack + 1:ipack + ((Ndata - ndone)*Nbits + 63)/64) = 0
         ibit = 0
         DO idata = ndone + 1, Ndata
            data_tmp = IAND(full_data(idata), mask)
            ioff = MOD(ibit, 64)
            packed_data(ipack + ibit/64 + 1) = IOR(packed_data(ipack + ibit/64 + 1), ISHFT(data_tmp, ioff))
            IF (ioff + Nbits > 64) packed_data(ipack + ibit/64 + 2) = ISHFT(data_tmp, ioff - 64)
            ibit = ibit + Nbits
         END DO
      END IF
   END SUBROUTINE ints2bits_tail

! **************************************************************************************************
!> \brief Unpacks the integers after the last whole group of 64 (fewer than 64 integers).
!> \param Nbits number of bits per integer
!> \param Ndata number of integers including the whole groups
!> \param packed_data the stream of bits
!> \param full_data the integers
! **************************************************************************************************
   SUBROUTINE bits2ints_tail(Nbits, Ndata, packed_data, full_data)
      INTEGER, INTENT(IN)                                :: Nbits, Ndata
      INTEGER(KIND=int_8), INTENT(IN)                    :: packed_data(*)
      INTEGER(KIND=int_8), INTENT(INOUT)                 :: full_data(*)

      INTEGER                                            :: ibit, idata, ipack, ioff, ndone
      INTEGER(KIND=int_8)                                :: mask, data_tmp

      ndone = (Ndata/64)*64
      IF (ndone < Ndata) THEN
         mask = ISHFT(1_int_8, Nbits) - 1 ! all bits if Nbits is 64
         ipack = (ndone/64)*Nbits
         ibit = 0
         DO idata = ndone + 1, Ndata
            ioff = MOD(ibit, 64)
            data_tmp = ISHFT(packed_data(ipack + ibit/64 + 1), -ioff)
            IF (ioff + Nbits > 64) data_tmp = IOR(data_tmp, ISHFT(packed_data(ipack + ibit/64 + 2), 64 - ioff))
            full_data(idata) = IAND(data_tmp, mask)
            ibit = ibit + Nbits
         END DO
      END IF
   END SUBROUTINE bits2ints_tail

! **************************************************************************************************
!> \brief Packs integers at a width per group, the width the group's largest magnitude needs:
!>        header bytes (the group size, then a width per group), then 8 interleaved streams
!>        (integer 8*c+l in stream l, all at the same bit position), so that every shift is
!>        uniform over the 8 lanes; a group is Ngroup/8 such columns at its width. The integers
!>        are signed, of Nbits bits (sign folded).
!> \param Nbits number of bits per integer (1 to 64); bits beyond them are ignored
!> \param Ngroup number of integers per group, a multiple of 8 (8 to 248)
!> \param packed_data the stream: words for 1+CEILING(n/Ngroup) header bytes, then at most
!>        8*CEILING(((n+7)/8)*Nbits/64) words (n integers)
!> \param full_data the integers
!> \return number of words written
! **************************************************************************************************
   FUNCTION ints2groups(Nbits, Ngroup, packed_data, full_data) RESULT(nwords)
      INTEGER, INTENT(IN)                                :: Nbits, Ngroup
      INTEGER(KIND=int_8), CONTIGUOUS, INTENT(OUT)       :: packed_data(:)
      INTEGER(KIND=int_8), CONTIGUOUS, INTENT(IN)        :: full_data(:)
      INTEGER                                            :: nwords

      INTEGER                                            :: b, c, i, j, lo, m, ncols, Ndata, &
                                                            ngroups, nhead, nmax, off, s, w
      INTEGER(KIND=int_8)                                :: z(256)

      CPASSERT(0 < Ngroup .AND. Ngroup <= 248 .AND. 0 == MOD(Ngroup, 8))
      Ndata = SIZE(full_data)
      ngroups = (Ndata + Ngroup - 1)/Ngroup
      nhead = (1 + ngroups + 7)/8
      nmax = nhead + 8*((((Ndata + 7)/8)*Nbits + 63)/64) ! words at most
      CPASSERT(nmax <= SIZE(packed_data))
      packed_data(1:nhead) = 0
      packed_data(1) = INT(Ngroup, KIND=int_8) ! group size
      s = 64 - Nbits
      j = 0
      off = 0
      DO i = 0, ngroups - 1
         m = MIN(Ngroup, Ndata - Ngroup*i)
         ncols = (m + 7)/8
         z(m + 1:8*ncols) = 0
         ! sign-extended from Nbits, then the sign folded (zig-zag)
         z(1:m) = SHIFTA(ISHFT(full_data(Ngroup*i + 1:Ngroup*i + m), s), s)
         z(1:m) = IEOR(ISHFT(z(1:m), 1), SHIFTA(z(1:m), 63))
         w = 64 - LEADZ(IANY(z(1:m)))
         b = i + 1 ! header byte of the width
         packed_data(b/8 + 1) = IOR(packed_data(b/8 + 1), ISHFT(INT(w, KIND=int_8), 8*MOD(b, 8)))
         IF (w > 0) THEN
            DO c = 0, ncols - 1
               lo = nhead + 8*j
               IF (off /= 0) THEN
                  packed_data(lo + 1:lo + 8) = IOR(packed_data(lo + 1:lo + 8), ISHFT(z(8*c + 1:8*c + 8), off))
               ELSE
                  packed_data(lo + 1:lo + 8) = z(8*c + 1:8*c + 8)
               END IF
               IF (off + w > 64) THEN ! spills into the next word
                  packed_data(lo + 9:lo + 16) = ISHFT(z(8*c + 1:8*c + 8), off - 64)
               END IF
               off = off + w
               IF (off >= 64) THEN
                  off = off - 64
                  j = j + 1
               END IF
            END DO
         END IF
      END DO
      nwords = nhead + 8*j
      IF (off /= 0) nwords = nwords + 8 ! partial last word
   END FUNCTION ints2groups

! **************************************************************************************************
!> \brief Unpacks integers that ints2groups packed (signed, the sign unfolded); the group size
!>        is read from the stream.
!> \param packed_data the stream
!> \param full_data the integers
!> \return number of words read
! **************************************************************************************************
   FUNCTION groups2ints(packed_data, full_data) RESULT(nwords)
      INTEGER(KIND=int_8), CONTIGUOUS, INTENT(IN)        :: packed_data(:)
      INTEGER(KIND=int_8), CONTIGUOUS, INTENT(OUT)       :: full_data(:)
      INTEGER                                            :: nwords

      INTEGER                                            :: b, base, c, i, j, lo, m, mc, Ndata, &
                                                            ngroup, ngroups, nhead, off, w
      INTEGER(KIND=int_8)                                :: mask, z(8)

      ngroup = INT(IAND(packed_data(1), 255_int_8))
      CPASSERT(0 < ngroup .AND. 0 == MOD(ngroup, 8))
      Ndata = SIZE(full_data)
      ngroups = (Ndata + ngroup - 1)/ngroup
      nhead = (1 + ngroups + 7)/8
      j = 0
      off = 0
      DO i = 0, ngroups - 1
         m = MIN(ngroup, Ndata - ngroup*i)
         b = i + 1 ! header byte of the width
         w = INT(IAND(ISHFT(packed_data(b/8 + 1), -8*MOD(b, 8)), 255_int_8))
         mask = ISHFT(-1_int_8, w - 64)
         DO c = 0, (m + 7)/8 - 1
            base = ngroup*i + 8*c
            mc = MIN(8, m - 8*c)
            IF (w > 0) THEN
               lo = nhead + 8*j
               IF (off + w > 64) THEN ! spills into the next word
                  z = IAND(IOR(ISHFT(packed_data(lo + 1:lo + 8), -off), ISHFT(packed_data(lo + 9:lo + 16), 64 - off)), mask)
               ELSE
                  z = IAND(ISHFT(packed_data(lo + 1:lo + 8), -off), mask)
               END IF
               off = off + w
               IF (off >= 64) THEN
                  off = off - 64
                  j = j + 1
               END IF
            ELSE
               z = 0
            END IF
            full_data(base + 1:base + mc) = IEOR(ISHFT(z(1:mc), -1), -IAND(z(1:mc), 1_int_8)) ! the sign unfolded
         END DO
      END DO
      nwords = nhead + 8*j
      IF (off /= 0) nwords = nwords + 8 ! partial last word
   END FUNCTION groups2ints

END MODULE hfx_compression_core_methods
