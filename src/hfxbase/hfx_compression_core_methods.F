! **************************************************************************************************
!> \brief Contains routines for data compression: packing integers of Nbits bits each into a
!>        stream of 64-bit words, and unpacking them. Per number of bits, fypp generates a
!>        routine that assembles each packed word in a register from constant shifts and stores
!>        it once, for every group of 64 integers (which fills exactly Nbits words).
!> \par History
!>      04.2008 created [Manuel Guidon]
!>      10.2026 generated by fypp instead of a generated source file [Hans Pabst]
!> \author Manuel Guidon
! **************************************************************************************************
MODULE hfx_compression_core_methods

   USE kinds, ONLY: int_8
#include "../base/base_uses.f90"

   IMPLICIT NONE
   PRIVATE

   PUBLIC :: bits2ints_specific, ints2bits_specific

CONTAINS

! **************************************************************************************************
!> \brief Packs integers into a stream of 64-bit words, Nbits bits per integer.
!> \param Nbits number of bits per integer (1 to 64); bits beyond them are ignored
!> \param Ndata number of integers
!> \param packed_data the stream of bits, CEILING(Ndata*Nbits/64) words
!> \param full_data the integers
! **************************************************************************************************
   SUBROUTINE ints2bits_specific(Nbits, Ndata, packed_data, full_data)
      INTEGER, INTENT(IN)                                :: Nbits, Ndata
      INTEGER(KIND=int_8), INTENT(OUT)                   :: packed_data(*)
      INTEGER(KIND=int_8), INTENT(IN)                    :: full_data(*)

      SELECT CASE (Nbits)
         #:for nb in range(1, 65)
            CASE (${nb}$)
            CALL ints2bits_${nb}$ (Ndata, packed_data, full_data)
         #:endfor
      CASE DEFAULT
         CPABORT("Invalid number of bits")
      END SELECT
   END SUBROUTINE ints2bits_specific

! **************************************************************************************************
!> \brief Unpacks integers from a stream of 64-bit words, Nbits bits per integer.
!> \param Nbits number of bits per integer (1 to 64)
