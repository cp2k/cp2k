! **************************************************************************************************
!> \brief Packs integers of ${nb}$ bits each (see ints2bits_specific).
!> \param Ndata ...
!> \param packed_data ...
!> \param full_data ...
! **************************************************************************************************
      SUBROUTINE ints2bits_${nb}$ (Ndata, packed_data, full_data)
         INTEGER, INTENT(IN)                                :: Ndata
         INTEGER(KIND=int_8), INTENT(OUT)                   :: packed_data(*)
         INTEGER(KIND=int_8), INTENT(IN)                    :: full_data(*)

         INTEGER(KIND=int_8), PARAMETER                     :: mask = ${mask}$_int_8

         INTEGER                                            :: igroup, ipack, idata
         INTEGER(KIND=int_8)                                :: pack_tmp

         DO igroup = 0, Ndata/64 - 1
            idata = 64*igroup
            ipack = ${nb}$*igroup
            #:for w in range(nb)
               #:set js = [j for j in range(64) if j*nb < 64*w + 64 and j*nb + nb > 64*w]
               pack_tmp = ISHFT(IAND(full_data(idata + ${js[0] + 1}$), mask), ${js[0]*nb - 64*w}$)
               #:for j in js[1:]
                  pack_tmp = IOR(pack_tmp, ISHFT(IAND(full_data(idata + ${j + 1}$), mask), ${j*nb - 64*w}$))
               #:endfor
               packed_data(ipack + ${w + 1}$) = pack_tmp
            #:endfor
         END DO
         CALL ints2bits_tail(${nb}$, Ndata, packed_data, full_data)
      END SUBROUTINE ints2bits_${nb}$

! **************************************************************************************************
!> \brief Unpacks integers of ${nb}$ bits each (see bits2ints_specific).
!> \param Ndata ...
!> \param packed_data ...
!> \param full_data ...
